'use strict';
// gen-fonts.js — vendor the UI's web fonts locally, so the app never reaches a font CDN at
// runtime and renders identically offline and on every machine. This is a one-time developer
// tool: it downloads the official open-licensed IBM Plex Sans and IBM Plex Mono woff2 files
// (SIL Open Font License) once, writes them into lib/public/fonts/, and regenerates fonts.css
// with matching @font-face rules. The downloaded files are committed; nothing here runs when
// the app runs. Re-run only to refresh the font set.
//
// Uses Node built-ins only (no extra dependency, no shelling out) so it works the same on
// macOS, Windows, and Linux. Run from the project root:  node lib/scripts/gen-fonts.js

const fs = require('fs');
const path = require('path');
const https = require('https');

const OUT_DIR = path.join(__dirname, '..', 'public', 'fonts');

// A desktop-Chrome User-Agent so the font service returns compact woff2 (an older UA gets
// larger legacy formats). Only latin subsets are kept — enough for English plus common
// accented names — which keeps the vendored set small.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600' +
  '&family=IBM+Plex+Mono:wght@400;500&display=swap';

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA } }, (r) => {
      if (r.statusCode !== 200) { r.resume(); return reject(new Error(`${r.statusCode} for ${url}`)); }
      const chunks = [];
      r.on('data', (c) => chunks.push(c));
      r.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

// Turn a family name into a short slug used in filenames and the @font-face family.
const slug = (family) => family.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

(async () => {
  console.log('Fetching font stylesheet…');
  const css = (await get(CSS_URL)).toString('utf-8');

  // The stylesheet emits, for each face, a `/* subset */` comment immediately followed by an
  // @font-face block. Capture the subset label with each block so we can keep only latin.
  const faceRe = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  const field = (body, name) => {
    const m = body.match(new RegExp(name + '\\s*:\\s*([^;]+);'));
    return m ? m[1].trim() : '';
  };

  fs.mkdirSync(OUT_DIR, { recursive: true });
  // Clear any previously vendored files so a re-run can't leave orphans behind.
  for (const f of fs.readdirSync(OUT_DIR)) {
    if (f.endsWith('.woff2') || f === 'fonts.css') fs.rmSync(path.join(OUT_DIR, f));
  }

  const rules = [];
  let count = 0, m;
  while ((m = faceRe.exec(css)) !== null) {
    const subset = m[1];
    if (!KEEP_SUBSETS.has(subset)) continue;
    const body = m[2];
    const family = field(body, 'font-family').replace(/^['"]|['"]$/g, '');
    const weight = field(body, 'font-weight') || '400';
    const style = field(body, 'font-style') || 'normal';
    const range = field(body, 'unicode-range');
    const urlMatch = body.match(/url\((https:[^)]+\.woff2)\)/);
    if (!urlMatch) continue;

    const fileName = `${slug(family)}-${weight}-${style}-${subset}.woff2`;
    process.stdout.write(`  ${fileName} … `);
    const bytes = await get(urlMatch[1]);
    fs.writeFileSync(path.join(OUT_DIR, fileName), bytes);
    console.log(`${Math.round(bytes.length / 1024)} KB`);

    rules.push(
      `@font-face {\n` +
      `  font-family: '${family}';\n` +
      `  font-style: ${style};\n` +
      `  font-weight: ${weight};\n` +
      `  font-display: swap;\n` +
      `  src: local('${family}'), url('/fonts/${fileName}') format('woff2');\n` +
      (range ? `  unicode-range: ${range};\n` : '') +
      `}`
    );
    count++;
  }

  if (!count) throw new Error('No font faces were extracted — the stylesheet format may have changed.');

  const header =
    '/* Locally vendored UI fonts — IBM Plex Sans and IBM Plex Mono (SIL Open Font License).\n' +
    '   Generated by lib/scripts/gen-fonts.js so the app serves its fonts itself and never\n' +
    '   contacts a font CDN at runtime. Do not edit by hand; re-run the generator instead. */\n\n';
  fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), header + rules.join('\n\n') + '\n');
  console.log(`\nWrote ${count} font files and fonts.css to ${OUT_DIR}`);
})().catch((e) => { console.error('gen-fonts failed:', e.message); process.exit(1); });
